#!/usr/bin/env python3
"""Turns TamaPoke.ino into plain C++ for the host simulator.

Arduino inserts a prototype for every function before the first function
definition. This script does the same with a simple scan of top-level function
definitions (one line, starting at column 0, ending with '{'). Default arguments
stay in the prototype and are removed from the definition, as C++ requires.

usage: ino2cpp.py TamaPoke.ino out.cpp
"""
import re
import sys

KEYWORDS = {'if', 'for', 'while', 'switch', 'return', 'else', 'do', 'case'}
DEF = re.compile(r'^(?P<head>(?:(?:static|inline|const|unsigned|struct)\s+)*[A-Za-z_][\w:<>]*\s*[\*&]*\s*'
                 r'(?<=[\s\*&])(?P<name>[A-Za-z_]\w*))\s*\((?P<args>[^;{}]*)\)\s*(?:const\s*)?\{\s*(?://.*)?$')


def strip_defaults(args):
    out, depth, cur = [], 0, ''
    for ch in args:
        if ch in '(<':
            depth += 1
        elif ch in ')>':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return ','.join(re.sub(r'\s*=\s*[^=].*$', '', a) for a in out)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    lines = open(src, encoding='utf-8').read().split('\n')
    protos, first = [], None
    in_block = 0
    for i, line in enumerate(lines):
        m = DEF.match(line)
        if m and in_block == 0 and m.group('name') not in KEYWORDS and not line.startswith(('else', 'return')):
            if first is None:
                first = i
            head, args = m.group('head'), m.group('args')
            protos.append(f'{head}({args});')
            if '=' in args:
                lines[i] = line.replace(f'({args})', f'({strip_defaults(args)})', 1)
        # rough brace depth (ignores braces in strings/comments well enough for this sketch)
        code = re.sub(r'"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'|//.*$', '', line)
        in_block += code.count('{') - code.count('}')
        if in_block < 0:
            in_block = 0
    if first is None:
        sys.exit('no functions found')
    out = lines[:first] + ['// ---- prototypes generated by tools/sim/ino2cpp.py ----'] + protos + \
        [f'#line {first + 1} "{src}"'] + lines[first:]
    with open(dst, 'w', encoding='utf-8') as f:
        f.write(f'#line 1 "{src}"\n' + '\n'.join(out))


if __name__ == '__main__':
    main()
